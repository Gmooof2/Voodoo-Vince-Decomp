"""Seed and check the retail unit config and symbol file (T10, phase 1.3).

CLI: units_seed.py --write [--force] | --check | --route --class C [--apply]   [--config P]
  --write: one unit per default.pdb module (689). Ownership from proto exec section contributions (runs of
    consecutive same-module records); main run = run with most own-proc bytes; edges pinned by LIS anchors over
    proto_map identical hits==1 rows and by anchor-window resolved ambiguous run-edge procs (anchor | neighbour |
    window | neighbour-window | unpinned-<class>); range, delink, delink_reason by the
    T10 rules (docs/ops/tools.md ## units_seed). Writes config/retail/units.toml and config/retail/symbols.txt
    (body-sha1 headers), prints counts, then runs --check on what it wrote.
  --check: validates both files (headers vs pin, unit keys/ranges/indices, symbol grammar/order/uniqueness/lint).
  --route --class C [--apply] (3.2 T8): T1's unit-edge route (docs/evidence/units.md "Unit-edge route") over the
    game units whose last seed item is in class C (ROUTE_CLASSES order); edges by `pin` (disasm-verified pin of the
    edge proc's PDB public), `chain`, `chain-neighbour`; outside procs explained as `moved` (between LIS anchors of
    one other unit's main run) or as another unit's chain proc; gap scans uncapped. Dry run prints the verdicts;
    --apply edits units.toml per unit block (released: range, edges, delink = true; kept: delink_reason
    "<item>; searched: <evidence>; fails: <why>"; old reason kept as a `# was:` line), never re-renders the file.
Files and prints hold names, addresses, counts and hashes only, never bytes (D46).
Exit: 0 ok; 1 validation or sum check failed; 2 refusal (input missing or != pin, hand-edited target without --force).
"""
