def _refuse(msg):
    print(f"units_seed: refused: {msg}", file=sys.stderr)
    sys.exit(2)


def _jsonl(path):
    if not path.is_file():
        _refuse(f"input missing: {path}")
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _hx(v):
    return f"0x{v:08X}"


def _tally(c):
    return ", ".join(f"{k} {v}" for k, v in sorted(c.items(), key=lambda kv: (-kv[1], str(kv[0])))) or "-"


# ---------------------------------------------------------------- inputs (pattern of xdk_report.py:105-139)
def load(cfg_path):
    cfg = vv_inputs.load_config(cfg_path)
    pin = coff_info.pinned_sha()
    if not pin:
        _refuse("no retail_xbe pin in config/check.retail_xbe.sha")
    xbe_b = vv_inputs.input_path("retail_xbe", cfg=cfg).read_bytes()
    if hashlib.sha1(xbe_b).hexdigest() != pin:
        _refuse("retail_xbe sha1 != pin")
    sha256 = hashlib.sha256(xbe_b).hexdigest()
    exe_b = vv_inputs.input_path("prototype_dir", "default.exe", cfg).read_bytes()
    pdb_b = vv_inputs.input_path("prototype_dir", "default.pdb", cfg).read_bytes()
    t5 = REPO / "derived" / "ghidra" / f"retail-{pin[:8]}"
    if not (PROTO / "summary.json").is_file() or not (t5 / "summary.json").is_file():
        _refuse(f"input missing: {PROTO / 'summary.json'} or {t5 / 'summary.json'}")
    psum = json.loads((PROTO / "summary.json").read_text(encoding="utf-8"))
    rows = _jsonl(PROTO / "functions.jsonl")
    if psum.get("targetSha1") != pin or any(r["targetSha1"] != pin for r in rows):
        _refuse("proto_map targetSha1 != pin")
    tsum = json.loads((t5 / "summary.json").read_text(encoding="utf-8"))
    if (tsum.get("executableSHA256") or "").lower() != sha256:
        _refuse("T5 summary executableSHA256 != sha256 of the pinned retail XBE")
    funcs = _jsonl(t5 / "functions.jsonl")
    syms = _jsonl(t5 / "symbols.jsonl")
    modrows = _jsonl(REPO / "derived" / "xdk" / f"retail-{pin[:8]}" / "modules.jsonl")
    if len(modrows) != NMOD:
        _refuse(f"xdk modules.jsonl has {len(modrows)} rows, want {NMOD}")
    try:
        x = xbe_info.parse_xbe(xbe_b)
        pe = pe_info.parse_pe(exe_b)
        pdb = pdb_info.parse_pdb(pdb_b)
    except (xbe_info.NotXbe, pe_info.NotPe, pdb_info.NotPdb) as e:
        _refuse(f"unparseable input: {e}")
    bad = pdb_info.validate(pdb, pe["rsds"])
    if bad:
        _refuse(f"default.pdb / default.exe pair invalid: {'; '.join(bad)}")
    if not pdb["contributions"]:
        _refuse("default.pdb has no section contributions")
    return {"pin": pin, "x": x, "pe": pe, "pdb": pdb, "rows": rows, "psum": psum, "funcs": funcs, "syms": syms,
            "modrows": modrows}


# ---------------------------------------------------------------- units (R2-R7)
def build_units(d, st, resolve=True):
    pe, pdb, rows = d["pe"], d["pdb"], d["rows"]
    base, secs = pe["imageBase"], pe["sections"]

    def pva(seg, off):
        return base + secs[seg - 1]["va"] + off if 1 <= seg <= len(secs) else None
    kind_of = {r["index"]: r["class"] for r in d["modrows"]}
    byva = {int(r["protoVA"], 16): r for r in rows}
    ident = [r for r in rows if r["class"] == "identical" and r["hits"] == 1]
    anc = proto_map.lis_anchors([(int(r["protoVA"], 16), int(r["targetVAs"][0], 16), r["length"]) for r in ident])
    if len(anc) != d["psum"].get("anchors"):
        print(f"units_seed: anchors {len(anc)} != proto_map summary anchors {d['psum'].get('anchors')}")
        sys.exit(1)
    anchor = {p: (t, n) for p, t, n in anc}
    st["anchors"] = len(anchor)

    # runs: exec contributions per section, sorted by offset, consecutive same-module records collapsed
    recs = [c for c in d["pdb"]["contributions"]["records"] if c["characteristics"] & CNT_CODE and c["size"] > 0]
    bysec = defaultdict(list)
    for c in recs:
        bysec[c["section"]].append(c)
    runs, rec_run, modruns = [], {}, defaultdict(list)
    for sec in sorted(bysec):
        prev = None
        for c in sorted(bysec[sec], key=lambda c: (c["offset"], c["module"])):
            if prev is not None and prev["module"] == c["module"]:
                prev["end"] = max(prev["end"], c["offset"] + c["size"])
            else:
                run = {"sec": sec, "start": c["offset"], "end": c["offset"] + c["size"], "module": c["module"],
                       "procs": [], "prev": prev, "next": None}
                if prev is not None:
                    prev["next"] = run
                runs.append(run)
                modruns[c["module"]].append(run)
                prev = run
            rec_run[id(c)] = prev
    modrecs = defaultdict(list)
    for c in recs:
        modrecs[(c["module"], c["section"])].append(c)

    # ownership
    own_c = folded_c = nosec_c = dup_c = 0
    modown = {}
    for m in pdb["modules"]:
        seen = {}
        for p in sorted(m["procs"], key=lambda p: (p["seg"], p["off"], p["name"])):
            va = pva(p["seg"], p["off"])
            if va is None:
                nosec_c += 1
                continue
            hit = next((c for c in modrecs.get((m["index"], p["seg"]), ())
                        if c["offset"] <= p["off"] and p["off"] + p["length"] <= c["offset"] + c["size"]), None)
            if hit is None:
                folded_c += 1
                continue
            own_c += 1
            if va in seen:
                dup_c += 1
                continue
            q = {"name": p["name"], "off": p["off"], "len": p["length"], "va": va, "run": rec_run[id(hit)]}
            seen[va] = q
            q["run"]["procs"].append(q)
        modown[m["index"]] = list(seen.values())
    for run in runs:
        run["procs"].sort(key=lambda q: (q["off"], q["name"]))
    st.update(own=own_c, folded=folded_c, nosec=nosec_c, dedup=dup_c,
              total=sum(len(m["procs"]) for m in pdb["modules"]))

    # anchor-window resolution of ambiguous run-edge procs (T10.c3): window = nearest LIS anchors in proto VA order,
    # same proto section; resolved iff uncapped, exactly one targetVA in the gap, at a proto-offset position
    res, rtally, apv = {}, Counter(), sorted(anchor)
    for run in runs if resolve else ():
        sb = base + secs[run["sec"] - 1]["va"]
        se = sb + secs[run["sec"] - 1]["vsize"]
        for q in {id(x): x for x in run["procs"][:1] + run["procs"][-1:]}.values():
            r = byva.get(q["va"])
            if r is None or r["class"] != "ambiguous":
                continue
            rtally["considered"] += 1
            k = bisect.bisect_left(apv, q["va"])
            pp = apv[k - 1] if k > 0 and sb <= apv[k - 1] < se else None
            nq = apv[k] if k < len(apv) and sb <= apv[k] < se else None
            tv = [int(v, 16) for v in r["targetVAs"]]
            if r["hits"] != len(tv):
                why = "capped"
            elif pp is None or nq is None:
                why = "no anchor on a side"
            else:
                (pt, pn), nt = anchor[pp], anchor[nq][0]
                ing = [v for v in tv if pt + pn <= v < nt]
                if not ing:
                    why = "no hit in gap"
                elif len(ing) > 1:
                    why = "several hits in gap"
                elif ing[0] not in (pt + (q["va"] - pp), nt - (nq - q["va"])):
                    why = "hit not at proto-offset position"
                else:
                    res[q["va"]] = ing[0]
                    rtally["resolved"] += 1
                    continue
            rtally["unresolved: " + why] += 1
    st["resolution"] = rtally

    def cls(q):
        r = byva.get(q["va"])
        return r["class"] if r else "no-row"

    def rva(q):
        return anchor[q["va"]][0]

    def rend(q):
        t, n = anchor[q["va"]]
        return t + n
    xsecs = [s for s in d["x"]["sections"] if s["flags"] & XBE_EXEC]
    units, split_mods, stray = [], Counter(), [0, 0]
    tail_mods, d24 = Counter(), []
    # main run per module first; tail of a section = runs starting at/after every main run's end there (C0020)
    mains = {}
    for m in pdb["modules"]:
        mr, own = modruns.get(m["index"], []), modown[m["index"]]
        if mr and own:
            mains[m["index"]] = max(mr, key=lambda r: (sum(q["len"] for q in r["procs"]), -r["sec"], -r["start"]))
    tail_start = {}
    for r in mains.values():
        tail_start[r["sec"]] = max(tail_start.get(r["sec"], 0), r["end"])
    st["tail_start"] = tail_start
    for m in pdb["modules"]:
        i = m["index"]
        kind = kind_of.get(i, "unknown")
        mr = modruns.get(i, [])
        u = {"name": m["name"], "index": i, "lib": m["obj"] or "", "objname": m["objname"] or "",
             "source": "proto-pdb:default.pdb", "kind": kind, "_range": None, "_edges": None, "_split": 0,
             "_incons": None, "procs_tail": 0}
        own = modown[i]
        main = None
        if not mr:
            u["range_reason"] = "no exec contribution"
        elif not own:
            u["range_reason"] = "no own procs"
        else:
            main = mains[i]
            nmain = sum(1 for q in own if q["run"] is main)
            u["procs_tail"] = sum(1 for q in own if q["run"] is not main
                                  and q["run"]["start"] >= tail_start[q["run"]["sec"]])
            u["_split"] = len(own) - nmain - u["procs_tail"]
            if nmain + u["procs_tail"] + u["_split"] != len(own) or u["_split"] != sum(
                    1 for q in own if q["run"] is not main and q["run"]["start"] < tail_start[q["run"]["sec"]]):
                d24.append(f"{m['name']}#{i}")
        if u["procs_tail"]:
            tail_mods[kind] += 1
        if kind == "game":
            for r in mr:
                if r is not main and not r["procs"]:
                    stray[0] += 1
                    stray[1] += r["end"] - r["start"]
        if u["_split"]:
            split_mods[kind] += 1
        if main is not None:
            pl = main["procs"]
            anch = [q for q in pl if q["va"] in anchor]
            if not anch:
                u["range_reason"] = "no anchor in main run"
                u["_main0"] = main  # route `no-range` only (pin anchors); `_main` stays unset (Route.owner reads it)
            else:
                pf, pz = pl[0], pl[-1]
                if pf["va"] in anchor and pf["off"] == main["start"]:
                    s, es = rva(pf), "anchor"
                elif pf["va"] in res and pf["off"] == main["start"]:
                    s, es = res[pf["va"]], "window"
                else:
                    pr = main["prev"]
                    q = next((q for q in reversed(pr["procs"]) if q["off"] + q["len"] == pr["end"]), None) \
                        if pr else None
                    if q is not None and q["va"] in anchor:
                        s, es = rend(q), "neighbour"
                    elif q is not None and q["va"] in res:
                        s, es = res[q["va"]] + q["len"], "neighbour-window"
                    else:
                        s = rva(anch[0])
                        es = "unpinned-" + ("noproc" if main["start"] < pf["off"] else cls(pf))
                if pz["va"] in anchor and pz["off"] + pz["len"] == main["end"]:
                    e, ee = rend(pz), "anchor"
                elif pz["va"] in res and pz["off"] + pz["len"] == main["end"]:
                    e, ee = res[pz["va"]] + pz["len"], "window"
                else:
                    nx = main["next"]
                    q = next((q for q in nx["procs"] if q["off"] == nx["start"]), None) if nx else None
                    if q is not None and q["va"] in anchor:
                        e, ee = rva(q), "neighbour"
                    elif q is not None and q["va"] in res:
                        e, ee = res[q["va"]], "neighbour-window"
                    else:
                        e = rend(anch[-1])
                        ee = "unpinned-" + ("noproc" if main["end"] > pz["off"] + pz["len"] else cls(pz))
                u["_edges"] = (es, ee)
                lo, hi = min([s] + [rva(q) for q in anch]), max([e] + [rend(q) for q in anch])
                if s < e and any(x["virtualAddr"] <= lo and hi <= x["virtualAddr"] + x["virtualSize"]
                                 for x in xsecs):
                    u["_range"] = (s, e)
                    u["_main"], u["_outs"] = main, []  # read by diagnostics only; never rendered
                    out = 0
                    for q in pl:
                        r = byva.get(q["va"])
                        if r is None:
                            continue
                        if r["class"] == "near-identical" and r["candidateVA"]:
                            v = int(r["candidateVA"], 16)
                        elif r["class"] == "identical" and r["hits"] == 1 and q["va"] not in anchor:
                            v = int(r["targetVAs"][0], 16)
                        else:
                            continue
                        out += not (s <= v < e)
                        if not (s <= v < e):
                            u["_outs"].append((q, r["class"], v))
                    u["_incons"] = out
                else:
                    u["range_reason"] = "spans retail sections"
                    st["nonpositive"] = st.get("nonpositive", 0) + (s >= e)
        u["procs"] = len(m["procs"])
        u["procs_identical"] = sum(1 for p in m["procs"] if (r := byva.get(pva(p["seg"], p["off"]))) is not None
                                   and r["class"] == "identical")
        c = m["compile"]
        u["_compile"] = c
        units.append(u)
    # overlaps: any two ranges that overlap drop both
    ranged = sorted((u for u in units if u["_range"]), key=lambda u: (u["_range"][0], u["index"]))
    over = defaultdict(list)
    for a_i, a in enumerate(ranged):
        for b in ranged[a_i + 1:]:
            if b["_range"][0] >= a["_range"][1]:
                break
            over[a["index"]].append(b)
            over[b["index"]].append(a)
    for u in ranged:
        if over[u["index"]]:
            o = over[u["index"]][0]
            u["range_reason"] = f"overlaps {o['name']}#{o['index']}"
    for u in ranged:
        if over[u["index"]]:
            u["_range"], u["_incons"] = None, None
    st["split_mods"], st["stray"], st["tail_mods"], st["d24"] = split_mods, stray, tail_mods, d24

    # delink (R6)
    for u in units:
        items = []
        if u["kind"] != "game":
            items.append(f"kind {u['kind']}")
        if not u["_range"]:
            items.append(f"no range: {u['range_reason']}")
        if u["_edges"]:
            for side, ek in zip(("start", "end"), u["_edges"]):
                if ek not in EDGE_OK:
                    items.append(f"edge {side} {ek}")
        if u["_split"]:
            items.append(f"split: {u['_split']} procs outside main run")
        if u["_incons"]:
            items.append(f"inconsistent: {u['_incons']} procs outside range")
        u["delink"] = not items
        if items:
            u["delink_reason"] = "; ".join(items)
    return units


def _tq(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif o < 0x20 or o == 0x7F:
            out.append(f"\\u{o:04X}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _tv(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return _tq(v)


def render_units(units, pin):
    ranged = sorted((u for u in units if u["_range"]), key=lambda u: (u["_range"][0], u["index"]))
    rest = sorted((u for u in units if not u["_range"]), key=lambda u: u["index"])
    blocks = []
    for u in ranged + rest:
        kv = [(k, _tv(u[k])) for k in ("name", "index", "lib", "objname", "source", "kind")]
        if u["_range"]:
            kv += [("text_start", _hx(u["_range"][0])), ("text_end", _hx(u["_range"][1])),
                   ("edge_start", _tq(u["_edges"][0])), ("edge_end", _tq(u["_edges"][1]))]
        else:
            kv.append(("range_reason", _tq(u["range_reason"])))
        kv += [("procs", _tv(u["procs"])), ("procs_identical", _tv(u["procs_identical"])),
               ("procs_tail", _tv(u["procs_tail"])), ("delink", _tv(u["delink"]))]
        if not u["delink"]:
            kv.append(("delink_reason", _tq(u["delink_reason"])))
        c = u["_compile"]
        if c == "missing":
            kv += [("language", _tq("missing")), ("machine", _tq("missing")), ("security_checks", _tq("missing")),
                   ("fltcg", _tq("missing"))]
        else:
            kv += [("language", _tq(c["language"])), ("machine", _tq(c["machine"])),
                   ("security_checks", _tv("securityChecks" in c["flagNames"])), ("fltcg", _tv(c["fLTCG"]))]
        kv.append(("opt", _tq("unknown")))
        blocks.append("[[unit]]\n" + "".join(f"{k} = {v}\n" for k, v in kv))
    body = "\n".join(blocks)
    return "\n".join([UNITS_GEN, f"# retail default.xbe sha1 {pin}", f"# body-sha1 {_sha(body)}"]) + "\n" + body


# ---------------------------------------------------------------- symbols (R9)
def build_symbols(d, drops):
    pe, rows = d["pe"], d["rows"]
    base, secs = pe["imageBase"], pe["sections"]
    mapcnt = Counter()
    for r in rows:
        if r["class"] in ("identical", "ambiguous"):
            for t in r["targetVAs"]:
                mapcnt[int(t, 16)] += 1
        elif r["class"] == "near-identical" and r["candidateVA"]:
            mapcnt[int(r["candidateVA"], 16)] += 1
    pubs = defaultdict(list)
    for p in d["pdb"]["publics"]:
        if 1 <= p["seg"] <= len(secs):
            pubs[base + secs[p["seg"] - 1]["va"] + p["off"]].append(p["name"])
    cands = []  # (va, prio, notprimary, name, kind, size, source)
    for r in rows:
        if r["class"] != "identical" or r["hits"] != 1:
            continue
        t = int(r["targetVAs"][0], 16)
        if mapcnt[t] > 1:
            drops["proto-pdb: retail VA mapped by another proto proc"] += 1
            continue
        names = pubs.get(int(r["protoVA"], 16), [])
        if len(names) != 1:
            drops[f"proto-pdb: S_PUB32 names at protoVA {'0' if not names else '>1'}"] += 1
            continue
        cands.append((t, 0, 0, names[0], "func", f"0x{r['length']:X}", "proto-pdb:default.pdb"))
    fsize = {int(f["entry"], 16): f["size"] for f in d["funcs"]}
    xs = [(s["virtualAddr"], s["virtualAddr"] + s["virtualSize"]) for s in d["x"]["sections"]]
    for s in d["syms"]:
        if not (s["xbsymdb"] or s["xtlid"]):
            continue
        if s["kernel"]:
            drops["label: kernel"] += 1
            continue
        va = int(s["va"], 16)
        if not any(a <= va < b for a, b in xs):
            drops["label: outside retail sections"] += 1
            continue
        src, prio = ("xbsymdb", 1) if s["xbsymdb"] else ("ghidra", 2)
        if va in fsize:
            cands.append((va, prio, 0 if s["primary"] else 1, s["name"], "func", f"0x{fsize[va]:X}", src))
        else:
            cands.append((va, prio, 0 if s["primary"] else 1, s["name"], "data", "-", src))
    keep = []
    for c in cands:
        if not c[3] or any(ch.isspace() for ch in c[3]):
            drops["name contains whitespace"] += 1
        else:
            keep.append(c)
    keep.sort()
    byva, names, out = set(), set(), []
    for c in keep:
        if c[0] in byva:
            drops["VA already named (precedence)"] += 1
            continue
        byva.add(c[0])
        out.append(c)
    final = []
    for c in sorted(out, key=lambda c: (c[0], c[3])):
        if c[3] in names:
            drops["name already used at lower VA"] += 1
            continue
        names.add(c[3])
        final.append(c)
    return [f"{_hx(c[0])} {c[4]} {c[5]} {c[3]} {c[6]} unverified" for c in final]


def render_symbols(lines, pin):
    body = "".join(line + "\n" for line in lines)
    return "\n".join([f"# retail default.xbe sha1 {pin}", SCOPE, GRAMMAR, GEN,
                      f"# body-sha1 {_sha(body)}"]) + "\n" + body


# ---------------------------------------------------------------- files, headers, check (R10, R11)
def _sha(body):
    return hashlib.sha1(body.encode("utf-8")).hexdigest()


def split_header(text):
    """(header lines, body text): header = leading '#' lines."""
    lines = text.split("\n")
    n = 0
    while n < len(lines) and lines[n].startswith("#"):
        n += 1
    return lines[:n], "\n".join(lines[n:])


def header_state(text):
    """(pin from header or None, recorded body sha1 or None, actual body sha1)."""
    head, body = split_header(text)
    pin = next((h.split()[-1] for h in head if h.startswith("# retail default.xbe sha1 ")), None)
    rec = next((h.split()[-1] for h in head if h.startswith("# body-sha1 ")), None)
    return pin, rec, _sha(body)


def gate_items(reason):
    return [s for s in reason.split("; ") if s]


def is_gate(u):  # game unit failing only on unpinned-ambiguous edges
    items = gate_items(u.get("delink_reason", "")) if u.get("kind") == "game" and u.get("delink") is False else []
    return bool(items) and all(s.startswith("edge ") and s.endswith(" unpinned-ambiguous") for s in items)


