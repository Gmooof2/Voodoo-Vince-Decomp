def check_text(utext, stext, pin):
    """Validate both files; prints notes and tallies; returns list of failures."""
    fails = []
    for label, text in (("units.toml", utext), ("symbols.txt", stext)):
        hp, rec, act = header_state(text)
        if hp != pin:
            fails.append(f"{label}: header sha1 {hp} != pin {pin}")
        if rec != act:
            print(f"note: {label} hand-edited (body-sha1 {rec} != {act})")
        else:
            print(f"{label}: body-sha1 {act} matches")
    try:
        units = tomllib.loads(utext).get("unit", [])
    except tomllib.TOMLDecodeError as e:
        return fails + [f"units.toml: TOML parse error: {e}"]
    if len(units) != NMOD:
        fails.append(f"units: {len(units)} != {NMOD}")
    if sorted(u.get("index") for u in units if isinstance(u.get("index"), int)) != list(range(NMOD)):
        fails.append("units: index set != 0..688")
    prev = None
    for u in units:
        tag = f"unit {u.get('name')}#{u.get('index')}"
        miss = [k for k in REQ if k not in u]
        if miss:
            fails.append(f"{tag}: missing keys {','.join(miss)}")
        if not (isinstance(u.get("procs_tail"), int) and not isinstance(u.get("procs_tail"), bool)
                and u["procs_tail"] >= 0):
            fails.append(f"{tag}: procs_tail not int >= 0")
        if u.get("kind") not in KINDS:
            fails.append(f"{tag}: kind {u.get('kind')!r}")
        has = "text_start" in u or "text_end" in u
        if has:
            if not (isinstance(u.get("text_start"), int) and isinstance(u.get("text_end"), int)):
                fails.append(f"{tag}: text_start/text_end not both ints")
                continue
            if u["text_start"] >= u["text_end"]:
                fails.append(f"{tag}: text_start >= text_end")
            if prev is not None:
                if u["text_start"] < prev["text_start"]:
                    fails.append(f"{tag}: ranged units not sorted by text_start")
                if u["text_start"] < prev["text_end"]:
                    fails.append(f"{tag}: range overlaps {prev.get('name')}#{prev.get('index')}")
            prev = u
        if ("edge_start" in u) != has or ("edge_end" in u) != has:
            fails.append(f"{tag}: edges present iff range violated")
        if has == ("range_reason" in u):
            fails.append(f"{tag}: range_reason iff no range violated")
        if u.get("delink") is True:
            if u.get("kind") != "game" or not has or u.get("edge_start") not in EDGE_OK \
                    or u.get("edge_end") not in EDGE_OK:
                fails.append(f"{tag}: delink=true without game kind, range and pinned edges")
        elif u.get("delink") is False:
            if not u.get("delink_reason"):
                fails.append(f"{tag}: delink=false with empty delink_reason")
        else:
            fails.append(f"{tag}: delink not bool")
    _, sbody = split_header(stext)
    lines = [line for line in sbody.split("\n") if line.strip()]
    last, vas, names = None, set(), set()
    for n, line in enumerate(lines, 1):
        f = line.split(" ")
        if len(f) != 6:
            fails.append(f"symbols line {n}: {len(f)} fields")
            continue
        va_s, kind, size, name, src, status = f
        if not re.fullmatch(r"0x[0-9A-F]{8}", va_s) or kind not in ("func", "data") \
                or not (size == "-" or re.fullmatch(r"0x[0-9A-Fa-f]+", size)):
            fails.append(f"symbols line {n}: grammar")
            continue
        va = int(va_s, 16)
        if last is not None and va < last:
            fails.append(f"symbols line {n}: not sorted by VA")
        last = va
        if va in vas:
            fails.append(f"symbols line {n}: duplicate VA {va_s}")
        if name in names:
            fails.append(f"symbols line {n}: duplicate name")
        vas.add(va)
        names.add(name)
        if src not in SOURCES:
            fails.append(f"symbols line {n}: source {src}")
        if status not in STATUSES:
            fails.append(f"symbols line {n}: status {status}")
        pm = PLACEHOLDER.match(name)
        if pm and int(pm.group(2), 16) != va:
            fails.append(f"symbols line {n}: placeholder {name} != VA {va_s}")
    print_tallies(units, lines)
    print(f"symbols: {len(lines)} lines; drops by reason: printed by --write only (not recorded in the files)")
    return fails


def do_check(pin):
    for p in (UNITS, SYMBOLS):
        if not p.is_file():
            _refuse(f"input missing: {p}")
    fails = check_text(UNITS.read_text(encoding="utf-8"), SYMBOLS.read_text(encoding="utf-8"), pin)
    for f in fails[:40]:
        print(f"FAIL {f}")
    print(f"check: {'ok' if not fails else f'{len(fails)} failures'}")
    return 1 if fails else 0


def do_write(cfg_path, force):
    for p in (UNITS, SYMBOLS):
        if p.is_file():
            _, rec, act = header_state(p.read_text(encoding="utf-8"))
            if rec != act and not force:
                _refuse(f"{p.relative_to(REPO)} hand-edited (body-sha1 {rec} != {act}); use --force")
    d = load(cfg_path)
    pin = d["pin"]
    st, drops = {}, Counter()
    units0 = build_units(d, {}, resolve=False)
    units = build_units(d, st)
    sym_lines = build_symbols(d, drops)
    fails = []

    def chk(label, got, want):
        ok = got == want
        fails.extend([] if ok else [label])
        print(f"  sum check {label}: {got} == {want} {'ok' if ok else 'FAIL'}")
    kinds = Counter(u["kind"] for u in units)
    chk("units == modules", len(units), len(d["pdb"]["modules"]))
    chk("modules == 689", len(d["pdb"]["modules"]), NMOD)
    chk("kinds sum", sum(kinds.values()), len(units))
    chk("own + folded + no-section == procs", st["own"] + st["folded"] + st["nosec"], st["total"])
    print(f"procs: total {st['total']} own {st['own']} (dup VA {st['dedup']}) folded {st['folded']} "
          f"no-section {st['nosec']}; split {sum(u['_split'] for u in units)} in "
          f"{sum(st['split_mods'].values())} units ({_tally(st['split_mods'])})")
    print("tail start per section: " + ", ".join(f"sec {k} +{_hx(v)}" for k, v in sorted(st["tail_start"].items())))
    print(f"procs_tail {sum(u['procs_tail'] for u in units)} in {sum(st['tail_mods'].values())} units "
          f"({_tally(st['tail_mods'])})")
    chk("own == main + tail + split (D24) mismatched units", len(st["d24"]), 0)
    print(f"stray runs (game modules): {st['stray'][0]} runs, {st['stray'][1]} bytes")
    print(f"units with range: {sum(1 for u in units if u['_range'])}; anchors {st['anchors']}"
          + (f"; non-positive ranges {st['nonpositive']}" if st.get("nonpositive") else ""))
    print("symbol drops: " + _tally(drops))
    gate0 = {u["index"] for u in units0 if is_gate(u)}
    rel = [u for u in units if u["index"] in gate0 and u["delink"]]
    other = sum(1 for a, b in zip(units0, units) if a["index"] not in gate0 and a["delink"] != b["delink"])
    print(f"window resolution: gate before {len(gate0)}; released {len(rel)} units, "
          f"{sum(u['_range'][1] - u['_range'][0] for u in rel)} bytes; still gated "
          f"{sum(1 for u in units if u['index'] in gate0 and not u['delink'])}; other delink changes {other}")
    print("resolution tally: " + _tally(st["resolution"]))
    if fails:
        print("units_seed: sum check failed; nothing written")
        return 1
    UNITS.parent.mkdir(parents=True, exist_ok=True)
    for p, text in ((UNITS, render_units(units, pin)), (SYMBOLS, render_symbols(sym_lines, pin))):
        old = p.read_text(encoding="utf-8") if p.is_file() else None
        _, _, act = header_state(text)
        print(f"{p.relative_to(REPO).as_posix()}: body-sha1 {act} {'unchanged' if old == text else 'written'}")
        if old != text:
            with open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    print("-- check of written files")
    return do_check(pin)


