def item_class(item):  # -> ROUTE_CLASSES index, or None (never routed: kind, no range, split, other edge kinds)
    if item.startswith("inconsistent: "):
        return 0
    if item == "edge end unpinned-ambiguous":
        return 1
    if item == "edge start unpinned-ambiguous":
        return 2
    for k, sfx in ((3, "unpinned-near-identical"), (4, "unpinned-identical"), (5, "unpinned-excluded"),
                   (5, "unpinned-absent")):
        if item.startswith("edge ") and item.endswith(" " + sfx):
            return k
    if item == "no range: no anchor in main run":
        return 6
    return None


def _short(u):
    return f"{u['name'].split(chr(92))[-1]}#{u['index']}"


class Route:
    """Retail evidence for the route: LIS anchors, main-run owners, disasm-verified pins, masked compare."""

    def __init__(self, d, seed, cur):
        import name_sites  # local: only the route needs the byte images
        cfg = vv_inputs.load_config(ARGS_CFG)
        exe = vv_inputs.input_path("prototype_dir", "default.exe", cfg).read_bytes()
        xb = vv_inputs.input_path("retail_xbe", cfg=cfg).read_bytes()
        self.im = name_sites.Images(exe, d["pe"], xb, d["x"])
        self.seed = seed
        self.byva = {int(r["protoVA"], 16): r for r in d["rows"]}
        ident = [r for r in d["rows"] if r["class"] == "identical" and r["hits"] == 1]
        anc = proto_map.lis_anchors([(int(r["protoVA"], 16), int(r["targetVAs"][0], 16), r["length"]) for r in ident])
        self.anchor = {p: (t, n) for p, t, n in anc}
        self.ancr = sorted((t, n, p) for p, t, n in anc)
        self.ancv = [a[0] for a in self.ancr]
        self.anc_at = {t: p for p, t, _n in anc}
        self.anc_end = {t + n: p for p, t, n in anc}
        self.ident_t = {int(r["targetVAs"][0], 16): int(r["protoVA"], 16) for r in ident}
        self.owner, self.proc = {}, {}
        for u in seed.values():
            for q in (u.get("_main") or {}).get("procs", ()):
                self.owner[q["va"]] = u["index"]
                self.proc[q["va"]] = q
        pe = d["pe"]
        base, secs = pe["imageBase"], pe["sections"]
        self.pubs = defaultdict(list)
        for p in d["pdb"]["publics"]:
            if 1 <= p["seg"] <= len(secs):
                self.pubs[base + secs[p["seg"] - 1]["va"] + p["off"]].append(p["name"])
        self.pins = {}  # name -> va, disasm-verified func pins only (D78: site-corr/unverified/boundary never fix)
        for line in PINS.read_text(encoding="utf-8").splitlines():
            f = line.split(" ")
            if not line.startswith("#") and len(f) == 6 and f[1] == "func" and f[5] == "disasm-verified":
                self.pins.setdefault(f[3], int(f[0], 16))
        self.pin_at = {v: n for n, v in self.pins.items()}
        self.pub_va = {n: v for v, ns in self.pubs.items() for n in ns}
        self.gf = sorted((int(r["entry"], 16), r["size"]) for r in d["funcs"])
        self.gfa = [g[0] for g in self.gf]
        self.ranged = sorted((u for u in cur if "text_start" in u), key=lambda u: u["text_start"])
        self.rstarts = [u["text_start"] for u in self.ranged]
        self.xsecs = [s for s in d["x"]["sections"] if s["flags"] & XBE_EXEC]
        self._chains, self._cpv = {}, None

    def unit_at(self, v):
        k = bisect.bisect_right(self.rstarts, v) - 1
        return self.ranged[k] if k >= 0 and v < self.ranged[k]["text_end"] else None

    def bracket(self, v):  # nearest LIS anchors (retail VA order) at/below and above v
        k = bisect.bisect_right(self.ancv, v) - 1
        return (self.ancr[k] if k >= 0 else None), (self.ancr[k + 1] if k + 1 < len(self.ancr) else None)

    def ghidra_body(self, v):  # decoy hint: v inside (not at) a Ghidra function body
        k = bisect.bisect_right(self.gfa, v) - 1
        return self.gf[k][0] if k >= 0 and self.gf[k][0] < v < self.gf[k][0] + self.gf[k][1] else None

    def unique_in_gap(self, q, pv, lo, hi):
        """Uncapped scan of [lo, hi): count retail positions masked-equal to proc q; True iff the only one is pv."""
        pb = self.im.pbytes(q["va"], q["len"])
        rb = self.im.rbytes(lo, hi - lo)
        if pb is None or rb is None:
            return False
        mp, _e = proto_map.mask_proc(pb, q["va"], self.im.plo, self.im.phi)
        masked = set()
        for o, w, _k in mp:
            masked.update(range(o, o + w))
        segs, a = [], None
        for i in range(q["len"] + 1):
            if i < q["len"] and i not in masked:
                a = i if a is None else a
            elif a is not None:
                segs.append((a, i))
                a = None
        hits = []
        for v in range(lo, hi - q["len"] + 1):
            o = v - lo
            if all(rb[o + x:o + y] == pb[x:y] for x, y in segs) and self.im.masked_equal(q["va"], v, q["len"]):
                hits.append(v)
                if len(hits) > 1:
                    break
        return hits == [pv]

    def chain(self, u, side):
        """-> (edge VA, kind, [(q, pv)], evidence) or (None, None, [], why). T1 `chain`/`chain-neighbour`."""
        key = (u["index"], side)
        if key in self._chains:
            return self._chains[key]
        self._chains[key] = r = self._chain(u, side)
        return r

    def _chain(self, u, side, pin=None):
        """pin: (proc index in main run, retail VA, label) replaces the LIS anchor (class `no-range`)."""
        main = u.get("_main") if pin is None else u.get("_main0")
        if not main:
            return None, None, [], "no main run with a range"
        pl = main["procs"]
        idx = [i for i, q in enumerate(pl) if q["va"] in self.anchor] if pin is None else [pin[0]]
        if side == "end":
            k = idx[-1]
            seq = pl[k + 1:]
            if pl[-1]["off"] + pl[-1]["len"] != main["end"]:
                return None, None, [], "run end is no proc end"
        else:
            k = idx[0]
            seq = pl[:k]
            if pl[0]["off"] != main["start"]:
                return None, None, [], "run start is no proc start"
        if not seq:
            return None, None, [], "edge proc is the anchor"
        a = pl[k]
        av = self.anchor[a["va"]][0] if pin is None else pin[1]
        base_r = av - a["va"]
        out = [(q, q["va"] + base_r) for q in seq]
        ev = f"{'anchor' if pin is None else pin[2]} {a['name'][:40]} 0x{av:08X}, {len(seq)} procs"
        for q, pv in out:
            if not self.im.masked_equal(q["va"], pv, q["len"]):
                return None, None, [], f"{ev}, {q['name'][:40]} not masked-equal at 0x{pv:08X}"
        gaps = defaultdict(list)
        for q, pv in out:
            lo_a, hi_a = self.bracket(pv)
            sec = next((s for s in self.xsecs if s["virtualAddr"] <= pv < s["virtualAddr"] + s["virtualSize"]), None)
            if sec is None:
                return None, None, [], f"{ev}, 0x{pv:08X} outside retail exec sections"
            lo = max(lo_a[0] + lo_a[1], sec["virtualAddr"]) if lo_a else sec["virtualAddr"]
            hi = min(hi_a[0], sec["virtualAddr"] + sec["virtualSize"]) if hi_a else \
                sec["virtualAddr"] + sec["virtualSize"]
            gaps[(lo, hi)].append((q, pv))
        for (lo, hi), qs in gaps.items():
            qs.sort(key=lambda t: t[1])
            filled = qs[0][1] == lo and qs[-1][1] + qs[-1][0]["len"] == hi and all(
                p[1] + p[0]["len"] == n[1] for p, n in zip(qs, qs[1:]))
            if filled:
                ev += f", gap 0x{lo:08X}-0x{hi:08X} exactly filled"
                continue
            for q, pv in qs:
                if not self.unique_in_gap(q, pv, lo, hi):
                    return None, None, [], f"{ev}, {q['name'][:40]} at 0x{pv:08X} not the only masked copy in gap " \
                                           f"0x{lo:08X}-0x{hi:08X} (uncapped scan)"
            ev += f", gap 0x{lo:08X}-0x{hi:08X} scanned, unique"
        if side == "end":
            e = out[-1][1] + out[-1][0]["len"]
            p = self.anc_at.get(e)
            nb = self.owner.get(p) if p is not None else self._pin_owner(e, None)
        else:
            e = out[0][1]
            p = self.anc_end.get(e)
            nb = self.owner.get(p) if p is not None else self._pin_owner(None, e)
        kind = "chain-neighbour" if nb is not None and nb != u["index"] else "chain"
        return e, kind, out, ev + (f", closes on {_short(self.seed[nb])}" if kind == "chain-neighbour" else "")

    def _pin_owner(self, start, end):  # disasm-verified pin of an adjacent unit's proc starting (ending) at the cut
        for n, v in self.pins.items():
            pva = self.pub_va.get(n)
            q = self.proc.get(pva) if pva is not None else None
            if q is None:
                continue
            if (start is not None and v == start) or (end is not None and v + q["len"] == end):
                return self.owner[pva]
        return None

    def edge_pin(self, u, side):  # disasm-verified pin named as the edge proc's PDB public: fixes it as an anchor
        main = u["_main"]
        pl = main["procs"]
        q = pl[-1] if side == "end" else pl[0]
        if side == "end" and q["off"] + q["len"] != main["end"] or side == "start" and q["off"] != main["start"]:
            return None
        for n in self.pubs.get(q["va"], ()):
            if n in self.pins:
                v = self.pins[n]
                return (v + q["len"] if side == "end" else v), f"pin {n[:60]} 0x{v:08X}"
        return None

    def chain_pv(self):  # retail VA -> (unit, proc) of every proc on a valid chain of any unit's unpinned edge
        if self._cpv is None:
            self._cpv = {}
            for u in self.seed.values():
                if not u.get("_main") or not u.get("_edges"):
                    continue
                for side, ek in zip(("start", "end"), u["_edges"]):
                    if ek not in EDGE_OK:
                        e, _k, out, _ev = self.chain(u, side)
                        for q, pv in out if e is not None else ():
                            self._cpv[pv] = (u, q)
        return self._cpv

    def explain(self, u, q, c, v):
        """Outside proc q of u, copy at v (class c). -> (None, evidence) explained, or (why, evidence)."""
        nm = f"{q['name'][:48]} proto 0x{q['va']:08X} -> 0x{v:08X}"
        if c != "identical":
            return "near-identical candidate, no single masked copy", nm
        lo, hi = self.bracket(v)
        ol = self.owner.get(lo[2]) if lo else None
        oh = self.owner.get(hi[2]) if hi else None
        if ol is not None and ol == oh and ol != u["index"] and v + q["len"] <= hi[0]:
            return None, f"{nm} moved into {_short(self.seed[ol])}"
        cp = self.chain_pv().get(v)
        if cp is not None and cp[0]["index"] != u["index"]:
            return None, f"{nm} chain proc of {_short(cp[0])}"
        f = lambda a, o: f"0x{a[0]:08X} {_short(self.seed[o]) if o is not None else 'no main run'}" if a else "-"
        ev = f"{nm}: single masked copy (proto_map hits 1), LIS bracket {f(lo, ol)} .. {f(hi, oh)}"
        ru = self.unit_at(v)
        ev += f", in {_short(ru)}" if ru else ", in no unit range"
        gb = self.ghidra_body(v)
        ev += f", inside Ghidra body 0x{gb:08X} (decoy hint)" if gb is not None else ""
        if ru is None:
            why = "copy in a gap between unit ranges"
        elif ol is None or oh is None:
            why = "bracket anchor in no unit's main run"
        elif ol == oh == u["index"]:
            why = "copy bracketed by own anchors"
        else:
            why = "copy bracketed by anchors of two different units"
        return why, ev

    def decide_norange(self, u):
        """Class `no-range`: pin anchors = main-run procs whose PDB public has a disasm-verified pin, masked-equal.
        Edge = the pin when the edge proc is pinned, else _chain from the first (start) / last (end) pin anchor.
        Every fail folds into one kept tuple under the original item, so a rerun still classes the unit `no-range`."""
        main = u["_main0"]
        pl = main["procs"]
        item = "no range: no anchor in main run"
        k1 = [q for q in pl if (r := self.byva.get(q["va"])) is not None and r["class"] == "identical"
              and r["hits"] == 1]
        dl = Counter(int(self.byva[q["va"]]["targetVAs"][0], 16) - q["va"] for q in k1)
        sx = lambda x: f"{'-' if x < 0 else '+'}0x{abs(x):X}"  # delta = retail VA - proto VA
        kd = " ".join(f"delta {sx(x)} x{n}" for x, n in sorted(dl.items(), key=lambda t: (-t[1], t[0])))
        pins, bad = [], []
        for i, q in enumerate(pl):
            n = next((n for n in self.pubs.get(q["va"], ()) if n in self.pins), None)
            if n is None:
                continue
            v = self.pins[n]
            (pins if self.im.masked_equal(q["va"], v, q["len"]) else bad).append((i, q, v, n))
        searched = f"LIS anchors 0, disasm-verified pins of {len(pl)} main-run procs {len(pins) + len(bad)}, " \
                   f"identical hits-1 copies {len(k1)}" + (f" ({kd})" if kd else "")
        fails = []  # (evidence, why)
        deltas = sorted({v - q["va"] for _i, q, v, _n in pins})
        if bad:
            fails += [(f"pin {n[:40]} 0x{v:08X}", "pin not masked-equal") for _i, _q, v, n in bad]
        elif not pins:
            fails.append((None, "no pin anchor"))
        elif len(deltas) > 1:
            fails.append((None, "pins disagree on delta " + " ".join(sx(x) for x in deltas)))
        else:
            searched += f", pin delta {sx(deltas[0])}"
        edges, se, notes, outs = [], [], [], []
        if not fails:
            for side in ("start", "end"):
                i, q, v, n = pins[0] if side == "start" else pins[-1]
                at = q["off"] == main["start"] if side == "start" else q["off"] + q["len"] == main["end"]
                if (i == 0 if side == "start" else i == len(pl) - 1) and at:
                    x, kind, ev = (v if side == "start" else v + q["len"]), "pin", f"pin {n[:60]} 0x{v:08X}"
                else:
                    x, kind, _out, ev = self._chain(u, side, (i, v, f"pin {n[:40]}"))
                    if x is None:
                        fails.append((f"{side}: {ev}", "pin chain fails"))
                        continue
                edges.append(kind)
                se.append(x)
                notes.append(f"{side} {kind}: {ev}")
        rng = tuple(se) if len(se) == 2 else None
        if rng is not None:
            s, e = rng
            rs = f"range 0x{s:08X}-0x{e:08X}"
            if not (s < e and any(x["virtualAddr"] <= s and e <= x["virtualAddr"] + x["virtualSize"]
                                  for x in self.xsecs)):
                fails.append((rs, "range empty or spans retail sections"))
            for t, p in sorted(self.ident_t.items()):
                if s <= t < e and self.owner.get(p) != u["index"]:
                    o = self.owner.get(p)
                    fails.append((rs, f"covers 0x{t:08X} of {_short(self.seed[o]) if o is not None else 'no main run'}"))
            for r in self.ranged:
                if r["index"] != u["index"] and r["text_start"] < e and s < r["text_end"]:
                    fails.append((rs, f"overlaps {_short(r)}"))
            for q in pl:
                r = self.byva.get(q["va"])
                if r is None:
                    continue
                if r["class"] == "near-identical" and r["candidateVA"]:
                    v = int(r["candidateVA"], 16)
                elif r["class"] == "identical" and r["hits"] == 1:
                    v = int(r["targetVAs"][0], 16)
                else:
                    continue
                if not (s <= v < e):
                    why, ev = self.explain(u, q, r["class"], v)
                    outs.append((why, ev))
                    if why is not None:
                        fails.append((ev, f"inconsistent: {why}"))
            notes += [ev for why, ev in outs if why is None]
        kept = []
        if fails:
            ev = [x for x, _w in fails if x is not None]
            kept = [(item, " | ".join([searched] + list(dict.fromkeys(ev))),
                     " | ".join(dict.fromkeys(w for _x, w in fails)))]
        return {"release": not kept, "range": rng, "edges": tuple(edges), "kept": kept, "notes": notes, "outs": outs}

    def decide(self, u):
        """-> dict(release, range, edges, kept [(item, searched, why)], notes)."""
        if u["_range"] is None:
            return self.decide_norange(u)
        s, e = u["_range"]
        edges = list(u["_edges"])
        kept, notes = [], []
        for i, side in enumerate(("start", "end")):
            if edges[i] in EDGE_OK:
                continue
            item = f"edge {side} {edges[i]}"
            pn = self.edge_pin(u, side)
            if pn is not None:
                v, ev = pn
                edges[i] = "pin"
            else:
                v, kind, _out, ev = self.chain(u, side)
                if v is None:
                    kept.append((item, ev, "no pin, chain fails"))
                    continue
                edges[i] = kind
            notes.append(f"{side} {edges[i]}: {ev}")
            if side == "start":
                s = v
            else:
                e = v
        rng = (s, e)
        if not kept:
            s0, e0 = u["_range"]
            for a, b in ((s, s0), (e0, e)):  # C0020: newly covered bytes hold only own procs
                for t, p in self.ident_t.items():
                    if a <= t < b and self.owner.get(p) != u["index"]:
                        o = self.owner.get(p)
                        kept.append((f"range 0x{s:08X}-0x{e:08X}", f"widened part 0x{a:08X}-0x{b:08X}",
                                     f"covers 0x{t:08X} of {_short(self.seed[o]) if o is not None else 'no main run'}"))
            for r in self.ranged:
                if r["index"] != u["index"] and r["text_start"] < e and s < r["text_end"]:
                    kept.append((f"range 0x{s:08X}-0x{e:08X}", "units.toml ranges", f"overlaps {_short(r)}"))
        outs, unexpl = [], []
        if not kept or all(k[0].startswith("range ") for k in kept):
            for q in u["_main"]["procs"]:
                r = self.byva.get(q["va"])
                if r is None:
                    continue
                if r["class"] == "near-identical" and r["candidateVA"]:
                    v = int(r["candidateVA"], 16)
                elif r["class"] == "identical" and r["hits"] == 1 and q["va"] not in self.anchor:
                    v = int(r["targetVAs"][0], 16)
                else:
                    continue
                if not (s <= v < e):
                    why, ev = self.explain(u, q, r["class"], v)
                    outs.append((why, ev))
                    if why is not None:
                        unexpl.append((why, ev))
            notes += [ev for why, ev in outs if why is None]
            if unexpl:
                item = f"inconsistent: {len(outs)} procs outside range, {len(outs) - len(unexpl)} explained"
                kept.append((item, " | ".join(ev for _w, ev in unexpl), " | ".join(w for w, _e in unexpl)))
        elif u["_incons"]:
            kept.append((f"inconsistent: {u['_incons']} procs outside range", "not searched", "edges not fixed"))
        return {"release": not kept, "range": rng, "edges": tuple(edges), "kept": kept, "notes": notes, "outs": outs}


def _reason(kept):
    return "; ".join(f"{i}; searched: {s}; fails: {w}" for i, s, w in kept)


def _edit_block(lines, u, dec):
    """Edit the unit's [[unit]] block in place (lines list). -> True if changed."""
    st = None
    for n, ln in enumerate(lines):
        if ln == "[[unit]]":
            st = n
        elif st is not None and ln == f"index = {u['index']}" and lines[n - 1] == f"name = {_tq(u['name'])}":
            break
    else:
        raise SystemExit(f"units_seed: block {_short(u)} not found")
    end = next((n for n in range(st + 1, len(lines)) if lines[n] == "[[unit]]"), len(lines))
    blk = lines[st:end]
    old = list(blk)

    def setk(k, val):
        i = next((i for i, x in enumerate(blk) if x.startswith(f"{k} = ")), None)
        if i is None:
            raise SystemExit(f"units_seed: {_short(u)} has no {k} line")
        blk[i] = f"{k} = {val}"
    ri = next((i for i, x in enumerate(blk) if x.startswith("delink_reason = ")), None)
    was = ri is not None and ri > 0 and blk[ri - 1].startswith("# was: delink_reason = ")
    if dec["release"] and not any(x.startswith("text_start = ") for x in blk):  # `no-range` release: add range lines
        ki = next((i for i, x in enumerate(blk) if x.startswith("kind = ")), None)
        rr = next((i for i, x in enumerate(blk) if x.startswith("range_reason = ")), None)
        if ki is None or rr is None:
            raise SystemExit(f"units_seed: {_short(u)} has no kind/range_reason line")
        blk[rr] = "# was: " + blk[rr]
        blk[ki + 1:ki + 1] = ["text_start = 0", "text_end = 0", "edge_start = 0", "edge_end = 0"]
        ri = next((i for i, x in enumerate(blk) if x.startswith("delink_reason = ")), None)
        was = ri is not None and ri > 0 and blk[ri - 1].startswith("# was: delink_reason = ")
    if dec["release"]:
        setk("text_start", _hx(dec["range"][0]))
        setk("text_end", _hx(dec["range"][1]))
        setk("edge_start", _tq(dec["edges"][0]))
        setk("edge_end", _tq(dec["edges"][1]))
        setk("delink", "true")
        if ri is not None:
            if was:
                del blk[ri]
            else:
                blk[ri] = "# was: " + blk[ri]
    else:
        new = f"delink_reason = {_tq(_reason(dec['kept']))}"
        if ri is None:
            raise SystemExit(f"units_seed: {_short(u)} kept but has no delink_reason line")
        if blk[ri] != new:
            if not was:
                blk.insert(ri, "# was: " + blk[ri])
                ri += 1
            blk[ri] = new
    lines[st:end] = blk
    if dec["release"] and old[0] == "[[unit]]" and not any(x.startswith("text_start = ") for x in old):
        # `no-range` release: move the block into the ranged section (ranged by text_start first, as --write renders)
        del lines[st:st + len(blk)]
        to = None
        for n, ln in enumerate(lines):
            if ln == "[[unit]]":
                ts = next((x for x in lines[n + 1:n + 12] if x.startswith("text_start = ") or x == "[[unit]]"), None)
                if ts is None or ts == "[[unit]]" or int(ts.split(" = ")[1], 16) > dec["range"][0]:
                    to = n
                    break
        if to is None:
            raise SystemExit(f"units_seed: {_short(u)} no insertion point")
        lines[to:to] = blk
    return blk != old


def do_route(cfg_path, cls, apply):
    global ARGS_CFG
    ARGS_CFG = cfg_path
    d = load(cfg_path)
    pin = d["pin"]
    seed = {u["index"]: u for u in build_units(d, {})}
    utext = UNITS.read_text(encoding="utf-8")
    cur = tomllib.loads(utext)["unit"]
    curi = {u["index"]: u for u in cur}
    ci = ROUTE_CLASSES.index(cls)
    sel = []
    for u in seed.values():
        if u["kind"] != "game" or u["delink"]:
            continue
        cl = [item_class(x) for x in gate_items(u["delink_reason"])]
        if None not in cl and max(cl) == ci:
            sel.append(u)
    sel.sort(key=lambda u: (u["_range"][0] if u["_range"] else 0, u["index"]))  # `no-range`: no seed range
    rt = Route(d, seed, cur)
    lines = utext.split("\n")
    before = sum(1 for u in sel if curi[u["index"]]["delink"] is True)
    rel, why_t, changed = [], Counter(), 0
    for u in sel:
        dec = rt.decide(u)
        c = curi[u["index"]]
        if dec["release"]:
            rel.append(u)
            same = c["delink"] is True and (c["text_start"], c["text_end"]) == dec["range"] \
                and (c["edge_start"], c["edge_end"]) == dec["edges"]
            print(f"RELEASE {_short(u)} 0x{dec['range'][0]:08X}-0x{dec['range'][1]:08X} {'/'.join(dec['edges'])}"
                  f"{' (units.toml already)' if same else ''}")
        else:
            for _i, _s, w in dec["kept"]:
                for x in w.split(" | "):
                    why_t[x] += 1
            print(f"KEEP {_short(u)}: {_reason(dec['kept'])}")
        for n in dec["notes"]:
            print(f"  {n}")
        if apply:
            changed += _edit_block(lines, u, dec)
    print(f"class {cls}: {len(sel)} units; delink=true before {before}, route releases {len(rel)}, keeps "
          f"{len(sel) - len(rel)}")
    print("kept by why: " + _tally(why_t))
    if not apply:
        return 0
    new = "\n".join(lines)
    fails = check_text(new, SYMBOLS.read_text(encoding="utf-8"), pin)
    if fails:
        for f in fails[:40]:
            print(f"FAIL {f}")
        print("units_seed: route result fails --check; units.toml not written")
        return 1
    if new != utext:
        with open(UNITS, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)
    print(f"{UNITS.relative_to(REPO).as_posix()}: {changed} unit blocks changed")
    return 0


